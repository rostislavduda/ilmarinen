# --------------------------------------------------------------------------- EQUIVARIANT (classification): ModelNet10
_MODELNET10_CLASSES = ("bathtub", "bed", "chair", "desk", "dresser", "monitor",
                       "night_stand", "sofa", "table", "toilet")


def _parse_off(path):
    """Minimal OFF mesh parser -> (vertices (V,3) float32, faces (F,3) int64). Handles the well-known ModelNet
    quirk where the 'OFF' header and the vertex/face/edge counts are glued together on the first line
    (e.g. 'OFF684 1240 0')."""
    with open(path) as fh:
        tok = fh.read().split()
    if tok[0] != "OFF":                                   # 'OFF684 ...' -> split the counts off the header
        tok[0] = tok[0][3:]; i = 0
    else:
        i = 1
    nV, nF = int(tok[i]), int(tok[i + 1]); i += 3         # i+2 is nE (unused)
    verts = np.array(tok[i:i + 3 * nV], dtype=np.float32).reshape(nV, 3); i += 3 * nV
    faces = []
    for _ in range(nF):
        k = int(tok[i]); faces.append([int(tok[i + 1]), int(tok[i + 2]), int(tok[i + 3])]); i += k + 1
    return verts, np.array(faces, dtype=np.int64)


def _sample_surface(verts, faces, n_pts, rng):
    """Area-weighted uniform surface sampling of a triangle mesh -> (n_pts,3), centered and scaled to the unit
    sphere. Triangles are drawn with probability proportional to area; a uniform barycentric point is taken via
    the sqrt(r1) parameterization."""
    v0, v1, v2 = verts[faces[:, 0]], verts[faces[:, 1]], verts[faces[:, 2]]
    areas = 0.5 * np.linalg.norm(np.cross(v1 - v0, v2 - v0), axis=1)
    areas = areas if areas.sum() > 0 else np.ones(len(faces))
    tri = rng.choice(len(faces), size=n_pts, p=areas / areas.sum())
    r1 = np.sqrt(rng.rand(n_pts))[:, None]; r2 = rng.rand(n_pts)[:, None]
    pts = (1 - r1) * v0[tri] + r1 * (1 - r2) * v1[tri] + r1 * r2 * v2[tri]
    pts = pts - pts.mean(0)
    return (pts / (np.linalg.norm(pts, axis=1).max() + 1e-8)).astype(np.float32)


def _knn_edges(pos, k):
    """k-nearest-neighbor directed edge index (2,E) int64 for a point cloud pos (n,3)."""
    n = len(pos)
    D = np.linalg.norm(pos[:, None] - pos[None], axis=-1)
    np.fill_diagonal(D, np.inf)
    kk = min(k, n - 1)
    idx = np.argpartition(D, kk, axis=1)[:, :kk]
    src = np.repeat(np.arange(n), kk); dst = idx.reshape(-1)
    return np.stack([src, dst]).astype(np.int64)


def load_modelnet10(reduced, device):
    """ModelNet10 (3D CAD point clouds, EQUIVARIANT contract) -- 10-class shape classification. Each mesh is
    area-weighted sampled to a point cloud, normalized to the unit sphere, and given 3D positions + a k-NN
    graph, so the allgraph routes to the SO(3)-equivariant contract. Fills the equivariant-CLASSIFICATION hole
    and adds a real, NON-chemistry equivariant dataset; a random rotation is applied at test time (true SO(3)
    generalization). Heavy first-time download (~450 MB from Princeton) with an uploaded ModelNet10.zip
    fallback; skips (FileNotFoundError) if neither is present."""
    import glob
    import os
    from .data_sources import modelnet10_dir
    from .allgraph import AllData
    root = modelnet10_dir()
    npts = 160 if reduced else 512
    rng = np.random.RandomState(0)

    def build(split, cap):
        NF, ED, POS, Y = [], [], [], []
        for ci, cname in enumerate(_MODELNET10_CLASSES):
            files = sorted(glob.glob(os.path.join(root, cname, split, "*.off")))
            if cap:
                files = files[:cap]
            for fp in files:
                try:
                    v, fc = _parse_off(fp)
                    if len(fc) == 0:
                        continue
                    pos = _sample_surface(v, fc, npts, rng)
                except Exception:
                    continue
                NF.append(np.ones((npts, 1), np.float32)); ED.append(_knn_edges(pos, 8))
                POS.append(pos); Y.append(ci)
        return NF, ED, POS, np.array(Y, np.int64)

    nf_tr, ed_tr, pos_tr, y_tr = build("train", qscale(30, lo=4) if reduced else None)   # 30/class x 10 = 300 train (rotated)
    nf_te, ed_te, pos_te, y_te = build("test", qscale(10, lo=3) if reduced else None)
    if len(y_tr) == 0 or len(y_te) == 0:
        raise FileNotFoundError("ModelNet10: no .off shapes found under the expected class/split folders")
    return {"train": AllData.graphs(nf_tr, ed_tr, y=y_tr, positions=pos_tr),
            "test": AllData.graphs(nf_te, ed_te, y=y_te, positions=pos_te),
            "task": "classification", "chance": 0.1, "field": "3D geometry (ModelNet10 CAD shapes)",
            "sota": "acc ~0.93-0.95 (PointNet++/DGCNN); rotation-robust variants lower", "rotated": True}


