def load_mnistangle(reduced, device):
    """MNIST rotation-angle regression (vision, SPATIAL contract). Real MNIST digits are each rotated by a known
    random angle in [-45,45] degrees; the target is that angle (standardized). REAL images with a genuinely
    continuous target -> exercises the spatial conv contract's REGRESSION head (the suite's only otherwise-
    uncovered spatial task). Semi-synthetic (real images, known target); MNIST is fetched via torchvision."""
    from .allgraph import AllData
    from .paths import data_dir
    from scipy.ndimage import rotate as _rotate
    import torch
    import torchvision
    root = data_dir()
    tr = torchvision.datasets.MNIST(root=root, train=True, download=True)
    te = torchvision.datasets.MNIST(root=root, train=False, download=True)

    def make(src, m, seed):
        rng = np.random.RandomState(seed)
        imgs = src.data.numpy().astype(np.float32) / 255.0
        sel = rng.permutation(len(imgs))[:m]
        ang = rng.uniform(-45, 45, len(sel)).astype(np.float32)
        X = np.zeros((len(sel), 1, 28, 28), np.float32)
        for k, (i, a) in enumerate(zip(sel, ang)):
            X[k, 0] = _rotate(imgs[i], a, reshape=False, order=1, mode="constant")
        return X, ang

    Xtr, atr = make(tr, qscale(1500) if reduced else 6000, 0)
    Xte, ate = make(te, qscale(1000) if reduced else 2000, 1)
    im_mu, im_sd = Xtr.mean(), Xtr.std() + 1e-8                # standardize intensities (as load_mnist does)
    Xtr = (Xtr - im_mu) / im_sd; Xte = (Xte - im_mu) / im_sd
    am, as_ = atr.mean(), atr.std() + 1e-8
    return {"train": AllData.dense_tensor(torch.tensor(Xtr), y=(atr - am) / as_),
            "test": AllData.dense_tensor(torch.tensor(Xte), y=(ate - am) / as_),
            "task": "regression", "chance": 0.0, "field": "vision (MNIST digit rotation-angle regression)",
            "sota": "R2 n/a (semi-synthetic; -> high for a CNN reading digit orientation)"}


# --------------------------------------------------------------------------- VOLUMETRIC (regression): 3D diffusion blob
def load_diffusionblob3d(reduced, device):
    """3D diffusion-blob width regression (physics, VOLUMETRIC contract). A point source diffuses in a 3D volume
    into an anisotropic Gaussian blob at a random location; the target is the blob's EFFECTIVE WIDTH (geometric
    mean of the per-axis sigmas), which requires reading the blob's 3D spatial extent (not a mean/sum). Fills
    the volumetric-REGRESSION hole. Solver/synthetic, no download."""
    from .allgraph import AllData
    import torch
    S = 16
    n = qscale(400) if reduced else 800
    rng = np.random.RandomState(0)
    ax = np.arange(S)
    X = np.zeros((n, 1, S, S, S), np.float32)
    y = np.zeros(n, np.float32)
    for i in range(n):
        c = rng.uniform(0.3, 0.7, 3) * S
        sig = rng.uniform(1.5, 4.0, 3).astype(np.float32)
        g = [np.exp(-0.5 * ((ax - c[d]) / sig[d]) ** 2) for d in range(3)]
        field = g[0][:, None, None] * g[1][None, :, None] * g[2][None, None, :]
        X[i, 0] = (field + 0.02 * rng.randn(S, S, S)).astype(np.float32)
        y[i] = float(np.cbrt(sig[0] * sig[1] * sig[2]))       # effective width (needs the 3D extent)
    y = (y - y.mean()) / (y.std() + 1e-8)
    ntr = int(0.8 * n)
    return {"train": AllData.dense_tensor(torch.tensor(X[:ntr]), y=y[:ntr]),
            "test": AllData.dense_tensor(torch.tensor(X[ntr:]), y=y[ntr:]),
            "task": "regression", "chance": 0.0, "field": "physics (3D diffusion-blob width, volumetric)",
            "sota": "R2 n/a (synthetic-from-solver; -> 1 for a sufficient 3D conv)"}


